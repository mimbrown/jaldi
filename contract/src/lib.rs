//! The contract between a framework and `jaldi`: what the framework hands
//! the tool ([`Manifest`]) and what the tool hands back ([`Answer`]).
//!
//! Both sides compile against this crate at one version. The tool refuses
//! a manifest written against another contract ([`Answer::Refused`]),
//! naming both, so drift is a launch error and never a silent one.
//! Changing anything here is a contract change: bump [`CONTRACT`],
//! release the tool, bump the framework's pin.
//!
//! The wire is JSON, one object each way. A manifest's first field is
//! `contract`; an answer's first two are `kind` and `contract`, at every
//! version, so a framework can read a refusal written by a tool it does
//! not otherwise understand.
//!
//! # What the tool writes
//!
//! Into `Manifest::out_dir`, named by the entry's id, which is one path
//! segment: `{id}.js` for an enhancement, `{id}.css` for a sheet, the
//! same with `.map` when the manifest asks for source maps, and
//! `{id}.json` holding the entry's [`Produced`] record. A framework reads
//! nothing else, and commits all of it beside the sources.

use std::fmt;
use std::path::PathBuf;

use serde::{Deserialize, Serialize};

/// The contract this crate describes. Equal on both sides or refused;
/// any difference is a refusal.
pub const CONTRACT: u32 = 1;

// ---------------------------------------------------------------- in

/// Everything the tool needs for one run. Generated by the framework from
/// its registry on every run; never written by hand, never configuration.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Manifest {
    /// The contract the manifest was written against. First field.
    pub contract: u32,
    /// The directory every relative path below resolves against: the
    /// framework's workspace root. Absolute.
    pub root: PathBuf,
    /// Where outputs go, relative to `root`. Committed beside the sources
    /// and verified by the framework's gate.
    pub out_dir: PathBuf,
    /// Whether to write a source map beside each output.
    pub source_maps: bool,
    pub entries: Vec<Entry>,
}

/// The oldest major version of each engine the output must run in.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Browsers {
    pub chrome: u16,
    pub safari: u16,
    pub firefox: u16,
}

/// One unit of work. Its id is the framework's name for it and the key
/// every output and diagnostic carries back.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Entry {
    pub id: EntryId,
    /// The Rust declaration this entry was generated from, so a diagnostic
    /// can point at the declaration rather than at generated text.
    pub origin: Origin,
    pub kind: Kind,
}

/// A framework-minted name, unique within one manifest and one path
/// segment (`chips`, `pattern-combobox`, `sheet`): it names the output
/// files. The tool refuses an id with a separator or a leading dot.
#[derive(Clone, PartialEq, Eq, Hash, Debug, Serialize, Deserialize)]
pub struct EntryId(pub String);

impl EntryId {
    /// Why this id cannot name a file, if it cannot.
    pub fn problem(&self) -> Option<&'static str> {
        let s = &self.0;
        if s.is_empty() {
            Some("is empty")
        } else if s.contains('/') || s.contains('\\') {
            Some("contains a path separator; an id is one path segment")
        } else if s.starts_with('.') {
            Some("starts with a dot")
        } else {
            None
        }
    }
}

impl fmt::Display for EntryId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// A Rust declaration site.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Origin {
    #[serde(rename = "crate")]
    pub krate: String,
    /// Relative to `Manifest::root`.
    pub file: PathBuf,
    pub line: u32,
}

/// What an entry is, and what its lowering needs. Each kind is lowered
/// one way; there is no verb to choose.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Kind {
    /// A TypeScript module authored against a generated header. Checked
    /// by the TypeScript 7 checker (strict, erasable syntax only, the
    /// module's default export pinned to the header's `Mount`), then
    /// lowered by erasure: the types removed and nothing else.
    Enhancement {
        /// Relative to `root`.
        source: PathBuf,
        /// The generated `{name}.parts.d.ts`, relative to `root`.
        header: PathBuf,
    },
    /// A stylesheet, composed by the framework. Lowered to the browser
    /// floor and minified; its rules come back as data for the
    /// framework's own checks.
    Sheet {
        source: Text,
        /// The custom properties the composition guarantees. A `var()`
        /// read of a property neither here nor declared in the sheet is
        /// a diagnostic.
        tokens: Vec<String>,
        /// The browser floor the sheet is lowered to. Demanded: a tool
        /// that guessed would guess differently from the framework's docs.
        browsers: Browsers,
    },
}

/// A text input: on disk, or already in memory (a sheet composed from
/// tokens, font faces, `base.css` and `css!` rules is never a file).
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
#[serde(tag = "text", rename_all = "snake_case")]
pub enum Text {
    /// Relative to `root`.
    File {
        path: PathBuf,
    },
    Inline {
        content: String,
    },
}

// ---------------------------------------------------------------- out

/// The tool's answer: one of these, as JSON on stdout.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum Answer {
    /// The run happened. Diagnostics may still carry errors; the exit
    /// status says so too ([`exit`]).
    Produced(Output),
    /// The manifest's contract is not this tool's. Nothing was read past
    /// the version, nothing was written. Frozen across versions: `kind`
    /// and `contract` (the tool's) lead, `manifest` is the version the
    /// manifest carried, `tool` names the tool.
    Refused { contract: u32, manifest: u32, tool: String },
}

#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Output {
    /// The tool's contract — the manifest's, since it was not refused.
    pub contract: u32,
    /// The tool's own version (`jaldi 0.1.0`), for the framework's pin check.
    pub tool: String,
    pub produced: Vec<Produced>,
    pub diagnostics: Vec<Diagnostic>,
}

/// What came of one entry. Absent from the list, and nothing written,
/// when the entry had an error diagnostic.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Produced {
    pub id: EntryId,
    /// SHA-256, hex, of everything the lowering read: for an enhancement
    /// the source then the header, concatenated; for a sheet its text.
    /// The framework computes the same ([`input_hash`]) to know when the
    /// output is behind.
    pub input_hash: Hash,
    /// Relative to `Manifest::out_dir`.
    pub output: PathBuf,
    pub output_hash: Hash,
    /// Relative to `out_dir`, when the manifest asked for maps.
    pub source_map: Option<PathBuf>,
    /// For a sheet: its rules as data, read off the lowered form.
    pub sheet: Option<SheetFacts>,
}

/// SHA-256, lowercase hex.
#[derive(Clone, PartialEq, Eq, Hash, Debug, Serialize, Deserialize)]
pub struct Hash(pub String);

#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct SheetFacts {
    pub rules: Vec<Rule>,
}

/// One style rule of the lowered sheet, enough for a framework's checks
/// that do not need the syntax tree: what it selects, in which layer, at
/// what specificity, and which properties it sets. A rule with several
/// selectors is one `Rule` per selector.
#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Rule {
    pub selector: String,
    /// The innermost `@layer` the rule sits in, dotted when nested.
    pub layer: Option<String>,
    /// `(ids, classes, types)`.
    pub specificity: (u32, u32, u32),
    /// Property names as written, custom properties included.
    pub properties: Vec<String>,
    /// In the input text.
    pub at: Position,
}

#[derive(Clone, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Diagnostic {
    /// The entry it is about; none for a problem with the run itself.
    pub entry: Option<EntryId>,
    pub severity: Severity,
    pub message: String,
    /// In the entry's input text (the source for an enhancement; a
    /// problem in the header or the lib names the file in the message).
    pub at: Option<Position>,
    /// Copied from the entry, so a printer needs nothing but this.
    pub origin: Option<Origin>,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    Error,
    Warning,
}

/// One-based line and column.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Serialize, Deserialize)]
pub struct Position {
    pub line: u32,
    pub column: u32,
}

// ---------------------------------------------------------------- wire

/// The hash a [`Produced::input_hash`] holds, over the inputs in order:
/// an enhancement's source then its header; a sheet's text alone.
pub fn input_hash(inputs: &[&[u8]]) -> Hash {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    for input in inputs {
        h.update(input);
    }
    Hash(format!("{:x}", h.finalize()))
}

/// Running the tool: the one convention both the framework's macro and
/// its server use. The binary is `$JALDI` when set (a local build while a
/// contract change is worked out), else `jaldi` on `PATH`. The manifest
/// goes in on stdin, the answer comes back on stdout.
pub mod invoke {
    use std::io::Write;
    use std::process::{Command, Stdio};

    use super::{Answer, Manifest};

    /// Why there is no answer.
    #[derive(Debug)]
    pub enum Failed {
        /// No `jaldi` on `PATH` and no `JALDI`: the message says how to get it.
        Absent,
        /// It ran but its output was not an answer; `BROKEN`, or worse.
        Broken { status: Option<i32>, stderr: String },
    }

    impl std::fmt::Display for Failed {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            match self {
                Failed::Absent => write!(
                    f,
                    "`jaldi` is not on PATH (and `JALDI` is unset): the frontend tool that checks and lowers \
                     enhancements. Install the pinned release (https://github.com/mimbrown/jaldi/releases) or \
                     point `JALDI` at a local build."
                ),
                Failed::Broken { status, stderr } => write!(f, "`jaldi` did not answer (status {status:?}): {}", stderr.trim()),
            }
        }
    }

    /// The binary that would run: `$JALDI`, else `jaldi`.
    pub fn program() -> String {
        std::env::var("JALDI")
            .ok()
            .filter(|s| !s.is_empty())
            .unwrap_or_else(|| "jaldi".to_string())
    }

    /// Run `jaldi lower` over the manifest. A refusal is an `Answer`, not
    /// a failure: the caller names both contracts.
    pub fn lower(manifest: &Manifest) -> Result<Answer, Failed> {
        let mut child = match Command::new(program())
            .args(["lower", "-"])
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
        {
            Ok(c) => c,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Err(Failed::Absent),
            Err(e) => {
                return Err(Failed::Broken {
                    status: None,
                    stderr: e.to_string(),
                });
            }
        };
        if let Some(mut stdin) = child.stdin.take() {
            let _ = stdin.write_all(manifest.to_json().as_bytes());
        }
        let out = child.wait_with_output().map_err(|e| Failed::Broken {
            status: None,
            stderr: e.to_string(),
        })?;
        let stdout = String::from_utf8_lossy(&out.stdout);
        Answer::from_json(&stdout).map_err(|_| Failed::Broken {
            status: out.status.code(),
            stderr: String::from_utf8_lossy(&out.stderr).into_owned(),
        })
    }
}

/// The tool's exit statuses, one per outcome a caller tells apart.
pub mod exit {
    /// Produced, no error diagnostics.
    pub const CLEAN: i32 = 0;
    /// Produced, at least one error diagnostic.
    pub const ERRORS: i32 = 1;
    /// Refused: the manifest's contract is not the tool's.
    pub const REFUSED: i32 = 2;
    /// The manifest could not be read or parsed, or an output could not
    /// be written. The message is on stderr.
    pub const BROKEN: i32 = 3;
}

#[derive(Deserialize)]
struct Leading {
    contract: u32,
}

/// The contract version a manifest carries, from its JSON, without
/// reading the rest.
pub fn manifest_version(json: &str) -> Result<u32, serde_json::Error> {
    serde_json::from_str::<Leading>(json).map(|l| l.contract)
}

impl Manifest {
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("a manifest serializes")
    }

    pub fn from_json(json: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json)
    }
}

impl Answer {
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("an answer serializes")
    }

    pub fn from_json(json: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json)
    }

    /// The exit status this answer goes with.
    pub fn exit_status(&self) -> i32 {
        match self {
            Answer::Produced(out) if out.diagnostics.iter().any(|d| d.severity == Severity::Error) => exit::ERRORS,
            Answer::Produced(_) => exit::CLEAN,
            Answer::Refused { .. } => exit::REFUSED,
        }
    }
}

impl Produced {
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("a record serializes")
    }

    pub fn from_json(json: &str) -> Result<Self, serde_json::Error> {
        serde_json::from_str(json)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest() -> Manifest {
        Manifest {
            contract: CONTRACT,
            root: PathBuf::from("/work/app"),
            out_dir: PathBuf::from("rubico-ats/base/.jaldi"),
            browsers: Browsers {
                chrome: 150,
                safari: 26,
                firefox: 148,
            },
            source_maps: false,
            entries: vec![
                Entry {
                    id: EntryId("chips".into()),
                    origin: Origin {
                        krate: "rubico-ats-base".into(),
                        file: "rubico-ats/base/src/ui/chips.rs".into(),
                        line: 12,
                    },
                    kind: Kind::Enhancement {
                        source: "rubico-ats/base/src/ui/chips.ts".into(),
                        header: "rubico-ats/base/src/ui/chips.parts.d.ts".into(),
                    },
                },
                Entry {
                    id: EntryId("sheet".into()),
                    origin: Origin {
                        krate: "rubico-ats-base".into(),
                        file: "rubico-ats/base/src/lib.rs".into(),
                        line: 40,
                    },
                    kind: Kind::Sheet {
                        source: Text::Inline {
                            content: ":root{--gap:1rem}".into(),
                        },
                        tokens: vec!["--gap".into()],
                    },
                },
            ],
        }
    }

    #[test]
    fn a_manifest_round_trips() {
        let m = manifest();
        assert_eq!(Manifest::from_json(&m.to_json()).unwrap(), m);
    }

    #[test]
    fn the_contract_leads_and_is_readable_alone() {
        let json = manifest().to_json();
        assert!(json.trim_start().starts_with("{\n  \"contract\": 1,"), "{json}");
        assert_eq!(manifest_version(&json).unwrap(), CONTRACT);
        // A manifest from a contract with fields this one has never seen
        // still yields its version.
        let other = r#"{"contract":7,"something":"new"}"#;
        assert_eq!(manifest_version(other).unwrap(), 7);
    }

    #[test]
    fn a_refusal_names_both_versions_and_reads_at_any_version() {
        let refused = Answer::Refused {
            contract: CONTRACT,
            manifest: 2,
            tool: "jaldi 0.1.0".into(),
        };
        let json = refused.to_json();
        assert!(json.starts_with("{\n  \"kind\": \"refused\",\n  \"contract\": 1,"), "{json}");
        assert_eq!(Answer::from_json(&json).unwrap(), refused);
        assert_eq!(refused.exit_status(), exit::REFUSED);
    }

    #[test]
    fn errors_change_the_exit_status() {
        let mut out = Output {
            contract: CONTRACT,
            tool: "jaldi 0.1.0".into(),
            produced: vec![],
            diagnostics: vec![],
        };
        assert_eq!(Answer::Produced(out.clone()).exit_status(), exit::CLEAN);
        out.diagnostics.push(Diagnostic {
            entry: None,
            severity: Severity::Warning,
            message: "w".into(),
            at: None,
            origin: None,
        });
        assert_eq!(Answer::Produced(out.clone()).exit_status(), exit::CLEAN);
        out.diagnostics.push(Diagnostic {
            entry: None,
            severity: Severity::Error,
            message: "e".into(),
            at: None,
            origin: None,
        });
        assert_eq!(Answer::Produced(out).exit_status(), exit::ERRORS);
    }

    #[test]
    fn kinds_are_tagged_on_the_wire() {
        let json = manifest().to_json();
        assert!(json.contains("\"kind\": \"enhancement\""), "{json}");
        assert!(json.contains("\"text\": \"inline\""), "{json}");
        assert!(json.contains("\"crate\": \"rubico-ats-base\""), "{json}");
    }

    #[test]
    fn an_id_is_one_path_segment() {
        assert_eq!(EntryId("chips".into()).problem(), None);
        assert_eq!(EntryId("pattern-combobox".into()).problem(), None);
        assert!(EntryId("pattern/combobox".into()).problem().is_some());
        assert!(EntryId("".into()).problem().is_some());
        assert!(EntryId(".hidden".into()).problem().is_some());
    }
}
